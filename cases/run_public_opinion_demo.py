def main():
    engine = CaseAnalysisEngine()
    result = engine.export_from_text(
        TITLE,
        BODY,
        overwrite=True,      # 正式交付：固定目录、只留 1 份
        tone="neutral",     # 或 "provocative"（仅封面标注）
    )
